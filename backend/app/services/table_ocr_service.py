
import json
from pathlib import Path

import cv2
import numpy as np
import pytesseract
from PIL import Image
from app.services.ocr_service import TESSERACT_PATH

pytesseract.pytesseract.tesseract_cmd = str(TESSERACT_PATH)

CROPS_DIR = Path("data/layout_crops")
OUTPUT_DIR = Path("data/table_extractions")


def extract_table_text(image_path: Path) -> dict:
    """Extract text from a detected table crop using OCR preprocessing."""
    image = cv2.imread(str(image_path))

    if image is None:
        raise ValueError(f"Could not read table image: {image_path}")

    gray = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)

    # Upscale to improve recognition of small table text.
    enlarged = cv2.resize(
        gray,
        None,
        fx=2,
        fy=2,
        interpolation=cv2.INTER_CUBIC,
    )

    processed = cv2.threshold(
        enlarged,
        0,
        255,
        cv2.THRESH_BINARY + cv2.THRESH_OTSU,
    )[1]

    ocr_data = pytesseract.image_to_data(
        processed,
        config="--oem 3 --psm 6",
        output_type=pytesseract.Output.DICT,
    )

    text = pytesseract.image_to_string(
        processed,
        config="--oem 3 --psm 6",
    ).strip()

    confidences = [
        float(value)
        for value, word in zip(
            ocr_data["conf"], ocr_data["text"]
        )
        if word.strip() and value not in ("-1", "")
    ]

    return {
        "text": text,
        "mean_word_confidence": (
            round(sum(confidences) / len(confidences), 2)
            if confidences else None
        ),
        "preprocessing": "grayscale_2x_otsu",
        "ocr_engine": "tesseract",
    }


def extract_document_tables(document_id: str) -> dict:
    """OCR all YOLO-detected tables for one uploaded document."""
    detections_path = Path("data/layout_detections") / f"{document_id}.json"

    if not detections_path.is_file():
        raise FileNotFoundError(
            f"Layout detections not found: {detections_path}"
        )

    with detections_path.open("r", encoding="utf-8") as file:
        layout_data = json.load(file)

    document_crop_dir = CROPS_DIR / document_id
    table_results = []

    for detection in layout_data.get("detections", []):
        if detection.get("label") != "Table":
            continue

        page_number = detection["page_number"]
        confidence = detection["confidence"]

        # Match the crop filename generated by layout_crop_service.
        crop_matches = sorted(
            document_crop_dir.glob(f"page_{page_number}_table_*.png")
        )

        if not crop_matches:
            continue

        # Use the crop with the highest matching detection confidence
        # when multiple table crops exist on a page.
        for crop_path in crop_matches:
            result = extract_table_text(crop_path)
            table_results.append({
                "page_number": page_number,
                "detection_confidence": confidence,
                "image_path": str(crop_path),
                **result,
            })

    output_dir = OUTPUT_DIR
    output_dir.mkdir(parents=True, exist_ok=True)
    output_path = output_dir / f"{document_id}.json"

    output = {
        "document_id": document_id,
        "table_count": len(table_results),
        "tables": table_results,
    }

    temporary_path = output_path.with_suffix(".tmp")
    try:
        with temporary_path.open("w", encoding="utf-8") as file:
            json.dump(output, file, ensure_ascii=False, indent=2)
        temporary_path.replace(output_path)
    finally:
        temporary_path.unlink(missing_ok=True)

    return {
        **output,
        "saved_to": str(output_path),
    }
